// Writes docs/ALIASES.md: every short alias in src/core/three-aliases.js and the
// three.js export it stands for (review finding I1: the bundle-derived sources
// use minifier names). Run: node tools/gen-alias-index.mjs
import fs from "node:fs";
import path from "node:path";
import { ROOT_DIR } from "./serve.mjs";

const src = fs.readFileSync(path.join(ROOT_DIR, "src/core/three-aliases.js"), "utf8");
const rows = [
  ...src.matchAll(/^\s+([A-Za-z_$][\w$]*) = (THREE(?:_ADDONS)?\.[\w$.]+)/gm),
].map((m) => [m[1], m[2]]);
rows.sort((a, b) => a[1].localeCompare(b[1]));
const out = [
  "# Alias index",
  "",
  "Generated by `node tools/gen-alias-index.mjs` from `src/core/three-aliases.js`. The machine, layer and simulator files that came from the v5 bundle use these short names. When reading one, look the name up here.",
  "",
  "| Alias | Stands for |",
  "| :---- | :--------- |",
  ...rows.map(([a, t]) => `| \`${a}\` | \`${t}\` |`),
  "",
].join("\n");
fs.writeFileSync(path.join(ROOT_DIR, "docs/ALIASES.md"), out);
console.log(`docs/ALIASES.md: ${rows.length} aliases`);
